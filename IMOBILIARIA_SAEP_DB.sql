CREATE DATABASE IF NOT EXISTS IMOBILIARIA_SAEP_DB;
USE IMOBILIARIA_SAEP_DB;

CREATE TABLE IF NOT EXISTS USUARIOS(
	USU_ID INT AUTO_INCREMENT PRIMARY KEY,
    USU_NOME VARCHAR(100) NOT NULL,
    USU_EMAIL VARCHAR(100) NOT NULL, 
    USU_SENHA VARCHAR(100) NOT NULL
);

CREATE TABLE IF NOT EXISTS PROPRIETARIOS(
	PRO_ID INT AUTO_INCREMENT PRIMARY KEY,
    PRO_NOME VARCHAR(100) NOT NULL,
    PRO_CPF VARCHAR(14) NOT NULL UNIQUE,
    PRO_TELEFONE VARCHAR(20) NOT NULL
);

CREATE TABLE IF NOT EXISTS IMOVEIS(
	IMO_ID INT AUTO_INCREMENT PRIMARY KEY,
    IMO_ENDERECO VARCHAR(10) NOT NULL UNIQUE,
    IMO_ANO INT NOT NULL,
    IMO_VALOR INT NOT NULL,
    FK_PRO_ID INT NOT NULL,
    FOREIGN KEY (FK_PRO_ID) REFERENCES PROPRIETARIOS(PRO_ID) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS AGENDAMENTOS(
	AGE_ID INT AUTO_INCREMENT PRIMARY KEY,
	AGE_DATA_HORA DATETIME NOT NULL,
    AGE_SERVICO VARCHAR(100) NOT NULL,
    AGE_STATUS VARCHAR(100) NOT NULL,
	FK_PRO_ID INT NOT NULL,
	FK_IMO_ID INT NOT NULL,
    FOREIGN KEY (FK_PRO_ID) REFERENCES PROPRIETARIOS(PRO_ID)  ON DELETE CASCADE,
	FOREIGN KEY (FK_IMO_ID) REFERENCES IMOVEIS(IMO_ID)  ON DELETE CASCADE
);

